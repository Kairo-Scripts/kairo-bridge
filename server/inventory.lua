--[[
    Item registry. Consumer scripts call Kairo.Inventory.RegisterItems(), which forwards definitions here.
    The bridge then:
      1. keeps a registry (used by standalone mode for labels / weights),
      2. writes paste-ready files to generated/ (ox_items.lua, qb_items.lua, esx_items.sql),
      3. warns about items missing from the active inventory.
]]
local Log = Kairo.Log
local resourceName = GetCurrentResourceName()

Kairo.ItemRegistry = Kairo.ItemRegistry or {}
local byResource = {}
local timer = false
local lastReport = ''

exports('GetRegisteredItem', function(name) return Kairo.ItemRegistry[name] end)

local function rebuild()
    local reg = {}
    for resource, list in pairs(byResource) do
        for _, def in ipairs(list) do
            def.resource = resource
            reg[def.name] = def
        end
    end
    Kairo.ItemRegistry = reg
end

local function sortedNames(reg)
    local names = {}
    for name in pairs(reg) do names[#names + 1] = name end
    table.sort(names)
    return names
end

local function lq(s) -- Lua single-quoted string
    s = tostring(s)
    s = s:gsub('\\', '\\\\')
    s = s:gsub("'", "\\'")
    s = s:gsub('\n', '\\n')
    return "'" .. s .. "'"
end
local function sq(s) -- SQL single-quoted string
    s = tostring(s):gsub("'", "''")
    return "'" .. s .. "'"
end

local function generate(reg)
    local names = sortedNames(reg)
    local header = '-- Generated by kairo-bridge. Do not edit; re-generated whenever scripts register items.'

    local ox = { header, '-- Paste these entries into ox_inventory/data/items.lua', '' }
    local qb = { header, '-- Paste these entries into qb-core/shared/items.lua (or your inventory\'s items file)', '' }
    local sql = { header, '-- For ESX native inventory. Adjust columns if your items table differs (e.g. `limit` instead of `weight`).', '' }

    for _, name in ipairs(names) do
        local d = reg[name]
        ox[#ox + 1] = ('[%s] = {'):format(lq(name))
        ox[#ox + 1] = ('    label = %s,'):format(lq(d.label))
        ox[#ox + 1] = ('    weight = %d,'):format(d.weight)
        ox[#ox + 1] = ('    stack = %s,'):format(tostring(d.stack))
        ox[#ox + 1] = ('    close = %s,'):format(tostring(d.close))
        if d.description ~= '' then ox[#ox + 1] = ('    description = %s,'):format(lq(d.description)) end
        if d.image ~= name .. '.png' then ox[#ox + 1] = ('    client = { image = %s },'):format(lq(d.image)) end
        ox[#ox + 1] = '},'

        qb[#qb + 1] = ('[%s] = { [\'name\'] = %s, [\'label\'] = %s, [\'weight\'] = %d, [\'type\'] = \'item\', [\'image\'] = %s, [\'unique\'] = %s, [\'useable\'] = %s, [\'shouldClose\'] = %s, [\'combinable\'] = nil, [\'description\'] = %s },')
            :format(lq(name), lq(name), lq(d.label), d.weight, lq(d.image), tostring(not d.stack), tostring(d.useable), tostring(d.close), lq(d.description))

        sql[#sql + 1] = ('INSERT IGNORE INTO `items` (`name`, `label`, `weight`) VALUES (%s, %s, %d);'):format(sq(name), sq(d.label), d.weight)
    end

    SaveResourceFile(resourceName, 'generated/ox_items.lua', table.concat(ox, '\n') .. '\n', -1)
    SaveResourceFile(resourceName, 'generated/qb_items.lua', table.concat(qb, '\n') .. '\n', -1)
    SaveResourceFile(resourceName, 'generated/esx_items.sql', table.concat(sql, '\n') .. '\n', -1)
end

local function sync()
    local reg = Kairo.ItemRegistry
    if next(reg) == nil then return end

    local ok, err = pcall(generate, reg)
    if not ok then Log.error('Could not write generated item files: %s', tostring(err)) end

    -- Which registered items does the active inventory not know about?
    local missing = {}
    local okCheck, checkErr = pcall(function()
        local Inventory = Kairo.Inventory
        for _, name in ipairs(sortedNames(reg)) do
            if not Inventory.ItemExists(name) then
                local r = reg[name].resource
                missing[r] = missing[r] or {}
                missing[r][#missing[r] + 1] = name
            end
        end
    end)
    if not okCheck then Log.warn('Item check skipped: %s', tostring(checkErr)) return end

    local lines = {}
    for resource, names in pairs(missing) do
        lines[#lines + 1] = ('%s: %s'):format(resource, table.concat(names, ', '))
    end
    table.sort(lines)
    local report = table.concat(lines, ' | ')
    if report ~= lastReport then
        lastReport = report
        if report ~= '' then
            local invName = Kairo.Env.inventory.name
            local file = ({ ox = 'ox_items.lua', qb = 'qb_items.lua', ps = 'qb_items.lua',
                            qs = 'qb_items.lua', codem = 'qb_items.lua', tgiann = 'qb_items.lua', core = 'qb_items.lua' })[invName]
                or (Kairo.Env.framework.name == 'esx' and 'esx_items.sql' or 'ox_items.lua')
            Log.warn('Items missing from your inventory -> %s', report)
            Log.warn('Paste the entries from %s/generated/%s, then restart your inventory/framework.', resourceName, file)
            if invName == 'qs' or invName == 'codem' or invName == 'tgiann' or invName == 'core' then
                Log.warn('%s keeps its own items file: the generated entries use the QB layout, so adapt the field names if yours differs.', invName)
            end
        end
    end
end

local function scheduleSync()
    if timer then return end
    timer = true
    SetTimeout(3000, function() -- debounce: let every consumer register first
        timer = false
        sync()
    end)
end

AddEventHandler('kairo-bridge:inventory:registerItems', function(resource, list)
    if type(resource) ~= 'string' or type(list) ~= 'table' then return end
    byResource[resource] = list
    rebuild()
    Log.debug('%s registered %d item(s)', resource, #list)
    scheduleSync()
end)
